// Converts the shared drawings in art/ into the forms this app uses. The SVG files themselves stay unchanged.
//
//   dart run tool/convert_art.dart
//
// It writes:
//   lib/src/ui/art_data.g.dart                     every icon and glyph's path data, for the Art widgets
//   android/app/src/main/res/drawable/ic_launcher_foreground.xml, ic_launcher_monochrome.xml
//   android/app/src/main/res/values/launcher.xml   the launcher's background colour
//   android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml
//   android/app/src/main/res/drawable/ic_stat_mossgrove.xml   the notification icon (art/icons/shop.svg)
//
// The iOS app icon is a picture, so it is drawn by tool/app_icon_test.dart instead (flutter test tool/app_icon_test.dart).
// Run both after changing anything in art/, and commit what they write.
import 'dart:io';

void main() {
  final root = Directory.current;
  final art = Directory('${root.path}/art');
  if (!art.existsSync()) {
    stderr.writeln('Run this from the repository root: art/ is not here.');
    exit(1);
  }

  final icons = _readSet(Directory('${art.path}/icons'));
  final glyphs = _readSet(Directory('${art.path}/glyphs'));
  _write('lib/src/ui/art_data.g.dart', _dart(icons, glyphs));

  final launcher = File('${art.path}/launcher.svg').readAsStringSync();
  final background = RegExp(r'<rect[^>]*fill="(#[0-9A-Fa-f]{6})"').firstMatch(launcher)!.group(1)!;
  final paths = RegExp(r'<path ([^>]*)/>').allMatches(launcher).map((m) => _attributes(m.group(1)!)).toList();
  final viewBox = RegExp(r'viewBox="0 0 (\d+) (\d+)"').firstMatch(launcher)!;
  final size = viewBox.group(1)!;

  _write('android/app/src/main/res/values/launcher.xml', '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/convert_art.dart from art/launcher.svg. Do not edit. -->
<resources>
    <color name="launcher_background">$background</color>
</resources>
''');

  final foreground = StringBuffer();
  final monochrome = StringBuffer();
  for (final p in paths) {
    foreground.writeln(_vectorPath(p));
    // the monochrome layer is one ink: a filled shape becomes its outline
    final outline = Map<String, String>.of(p);
    if (outline['fill'] != null && outline['fill'] != 'none') {
      outline['fill'] = 'none';
      outline['stroke-width'] = '3';
    }
    outline['stroke'] = '#000000';
    monochrome.writeln(_vectorPath(outline));
  }
  _write(
    'android/app/src/main/res/drawable/ic_launcher_foreground.xml',
    _vector(size, foreground.toString(), 'art/launcher.svg'),
  );
  _write(
    'android/app/src/main/res/drawable/ic_launcher_monochrome.xml',
    _vector(size, monochrome.toString(), 'art/launcher.svg'),
  );
  _write('android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml', '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/convert_art.dart from art/launcher.svg. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''');

  final shop = icons['shop']!;
  _write(
    'android/app/src/main/res/drawable/ic_stat_mossgrove.xml',
    _vector(
      '${shop.viewBox.toInt()}',
      _vectorPath({
        'd': shop.data,
        'fill': 'none',
        'stroke': '#FFFFFF',
        'stroke-width': _number(shop.stroke),
        'stroke-linecap': 'round',
        'stroke-linejoin': 'round',
      }),
      'art/icons/shop.svg',
    ),
  );
}

class _Drawing {
  _Drawing(this.viewBox, this.stroke, this.data);

  final double viewBox;
  final double stroke;
  final String data;
}

Map<String, _Drawing> _readSet(Directory dir) {
  final files = dir.listSync().whereType<File>().where((f) => f.path.endsWith('.svg')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  return {for (final file in files) file.uri.pathSegments.last.replaceAll('.svg', ''): _parse(file)};
}

_Drawing _parse(File file) {
  final svg = file.readAsStringSync();
  final viewBox = RegExp(r'viewBox="0 0 ([\d.]+) ([\d.]+)"').firstMatch(svg);
  final stroke = RegExp(r'stroke-width="([\d.]+)"').firstMatch(svg);
  final paths = RegExp(r'<path d="([^"]+)"').allMatches(svg).toList();
  if (viewBox == null || stroke == null || paths.length != 1) {
    throw FormatException('${file.path}: expected one stroked path in a square viewBox');
  }
  return _Drawing(double.parse(viewBox.group(1)!), double.parse(stroke.group(1)!), paths.single.group(1)!);
}

Map<String, String> _attributes(String text) => {
  for (final m in RegExp(r'([a-z-]+)="([^"]*)"').allMatches(text)) m.group(1)!: m.group(2)!,
};

String _number(double value) => value == value.roundToDouble() ? value.toInt().toString() : value.toString();

String _vector(String size, String paths, String source) =>
    '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/convert_art.dart from $source. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size}dp" android:height="${size}dp" android:viewportWidth="$size" android:viewportHeight="$size">
${paths.trimRight()}
</vector>
''';

String _vectorPath(Map<String, String> a) {
  final fill = a['fill'];
  final out = StringBuffer('    <path');
  out.write(' android:fillColor="${fill == null || fill == 'none' ? '#00000000' : _argb(fill)}"');
  if (a['stroke'] != null) {
    out.write(' android:strokeColor="${_argb(a['stroke']!)}" android:strokeWidth="${a['stroke-width'] ?? '1'}"');
  }
  if (a['stroke-linecap'] != null) out.write(' android:strokeLineCap="${a['stroke-linecap']}"');
  if (a['stroke-linejoin'] != null) out.write(' android:strokeLineJoin="${a['stroke-linejoin']}"');
  out.write('\n        android:pathData="${a['d']}" />');
  return out.toString();
}

String _argb(String hex) => '#FF${hex.substring(1).toUpperCase()}';

String _dart(Map<String, _Drawing> icons, Map<String, _Drawing> glyphs) {
  final out = StringBuffer()
    ..writeln('// Generated by tool/convert_art.dart from art/icons/*.svg and art/glyphs/*.svg. Do not edit.')
    ..writeln('//')
    ..writeln('// Each drawing is one stroked path, drawn for the Mossgrove apps; the colour comes from the theme.')
    ..writeln('// One drawing per line, as the converter writes it: CI regenerates this file and compares.')
    ..writeln('// dart format off')
    ..writeln()
    ..writeln("import 'art.dart';")
    ..writeln();
  void set(String name, String doc, Map<String, _Drawing> drawings) {
    out.writeln('/// $doc');
    out.writeln('const Map<String, ArtDrawing> $name = {');
    drawings.forEach((key, d) {
      out.writeln("  '$key': ArtDrawing(${_number(d.viewBox)}, ${_number(d.stroke)}, '${d.data}'),");
    });
    out.writeln('};');
  }

  set('iconDrawings', 'Interface icons, 24 units with a 2-unit stroke (art/icons).', icons);
  out.writeln();
  set('glyphDrawings', 'Product drawings, 48 units with a 2.5-unit stroke (art/glyphs).', glyphs);
  return out.toString();
}

void _write(String path, String content) {
  final file = File(path);
  file.parent.createSync(recursive: true);
  file.writeAsStringSync(content);
  stdout.writeln('wrote $path');
}
